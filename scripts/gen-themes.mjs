/* ── colour math ─────────────────────────────────────────── */
const hex2rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const rgb2hex = (c) => '#' + c.map((v) => Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, '0')).join('');
const lin = (v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const delin = (v) => (v <= 0.0031308 ? v * 12.92 : 1.055 * v ** (1 / 2.4) - 0.055);

function lum(h) {
	const [r, g, b] = hex2rgb(h).map(lin);
	return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
function contrast(a, b) {
	const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
	return (x + 0.05) / (y + 0.05);
}
function hex2oklch(h) {
	const [r, g, b] = hex2rgb(h).map(lin);
	const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
	const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
	const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
	const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
	const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
	const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
	return { L, C: Math.hypot(A, B), H: ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360 };
}
function oklch2hex({ L, C, H }) {
	const A = C * Math.cos((H * Math.PI) / 180);
	const B = C * Math.sin((H * Math.PI) / 180);
	const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
	const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
	const s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
	return rgb2hex([
		4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
		-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
		-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
	].map(delin));
}
const mix = (a, b, t) => rgb2hex(hex2rgb(a).map((v, i) => v * (1 - t) + hex2rgb(b)[i] * t));
const fmt = (h) => {
	const { L, C, H } = hex2oklch(h);
	return `${(L * 100).toFixed(1)}% ${C.toFixed(3)} ${(C < 0.004 ? 0 : H).toFixed(0)}`;
};

/** Move colour along OKLCH lightness (away from bg) until `min` contrast on ALL bgs. */
function ensure(fg, bgs, min) {
	const ok = (c) => bgs.every((b) => contrast(c, b) >= min);
	if (ok(fg)) return { hex: fg, moved: false };
	const o = hex2oklch(fg);
	const darkBg = bgs.every((b) => lum(b) < 0.3);
	for (let i = 1; i <= 100; i++) {
		const L = darkBg ? Math.min(1, o.L + i * 0.005) : Math.max(0, o.L - i * 0.005);
		const c = oklch2hex({ ...o, L });
		if (ok(c)) return { hex: c, moved: true };
	}
	return { hex: darkBg ? '#ffffff' : '#000000', moved: true };
}
const onColor = (bg, cands) => cands.map((c) => [c, contrast(c, bg)]).sort((a, b) => b[1] - a[1])[0][0];

