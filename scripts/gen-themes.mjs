const SHAPE_LIGHT = ['--rounded-box: 0.85rem', '--rounded-btn: 0.55rem'];

function build(t) {
	const bgs = [t.b1, t.b2];
	const dark = t.group === 'dark';
	const notes = [];
	const text = ensure(t.bc, bgs, 7);
	if (text.moved) notes.push(`bc ${t.bc}→${text.hex}`);
	const bc = text.hex;
	const accent = ensure(t.p, bgs, 4.5);
	if (accent.moved) notes.push(`p ${t.p}→${accent.hex}`);
	const p = accent.hex;

	const pair = (c) => [c, onColor(c, [t.b1, bc, '#ffffff', '#000000'])];
	const [s, sc] = pair(t.s);
	const [a, ac] = pair(t.a);
	const [su, suc] = pair(t.su);
	const [wa, wac] = pair(t.wa);
	const [er, erc] = pair(t.er);
	const pc = onColor(p, [t.b1, bc, '#ffffff', '#000000']);
	const inline = ensure(bc, [mix(t.b2, t.b3, 0.55)], 7).hex;

	const vars = {
		p: fmt(p), pf: fmt(mix(p, dark ? '#ffffff' : '#000000', 0.12)), pc: fmt(pc),
		s: fmt(s), sf: fmt(mix(s, dark ? '#ffffff' : '#000000', 0.12)), sc: fmt(sc),
		a: fmt(a), af: fmt(mix(a, dark ? '#ffffff' : '#000000', 0.12)), ac: fmt(ac),
		n: fmt(bc), nf: fmt(mix(bc, t.b1, 0.15)), nc: fmt(t.b1),
		b1: fmt(t.b1), b2: fmt(t.b2), b3: fmt(t.b3), bc: fmt(bc),
		in: fmt(s), inc: fmt(sc),
		su: fmt(su), suc: fmt(suc), wa: fmt(wa), wac: fmt(wac), er: fmt(er), erc: fmt(erc),
	};
	const css = [
		`html[data-theme="${t.id}"] {`,
		`  color-scheme: ${dark ? 'dark' : 'light'};`,
		'  ' + Object.entries(vars).map(([k, v]) => `--${k}: ${v};`).join('\n  '),
		`  --rtlmd-inline-code-bg: ${mix(t.b2, t.b3, 0.55)};`,
		`  --rtlmd-inline-code-fg: ${inline};`,
		`  --rtlmd-inline-code-border: ${t.b3};`,
		`  --rtlmd-block-code-bg: ${t.code};`,
		`  --rtlmd-block-code-border: ${mix(t.code, '#ffffff', 0.16)};`,
		`  --rtlmd-table-border: ${mix(t.b3, bc, 0.12)};`,
		`  --rtlmd-table-head-bg: ${mix(t.b2, t.b3, 0.5)};`,
		`  --rtlmd-table-row-alt: ${mix(t.b2, t.b3, 0.22)};`,
		'}',
	].join('\n');

	const rep = {
		id: t.id,
		text: Math.min(contrast(bc, t.b1), contrast(bc, t.b2)),
		link: Math.min(contrast(p, t.b1), contrast(p, t.b2)),
		btn: contrast(pc, p),
		notes: notes.join(', '),
	};
	return { css, rep };
}

const built = THEMES.map(build);

